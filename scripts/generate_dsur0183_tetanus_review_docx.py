def h(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    return p


def para(doc, text, bold_prefix: str | None = None, size=10.5, space_after=4):
    p = doc.add_paragraph()
    run = p.add_run()
    if bold_prefix:
        r = p.add_run(bold_prefix)
        r.bold = True
        r.font.size = Pt(size)
    r2 = p.add_run(text)
    r2.font.size = Pt(size)
    p.paragraph_format.space_after = Pt(space_after)
    return p


def finding(doc, code, severity, location, current, issue, basis, suggestion):
    p = doc.add_paragraph()
    r = p.add_run(f"{code}　")
    r.bold = True
    r.font.size = Pt(10.5)
    r2 = p.add_run(f"【{severity}】")
    r2.bold = True
    r2.font.color.rgb = SEV_COLOR.get(severity, RGBColor(0, 0, 0))
    r2.font.size = Pt(10.5)
    r3 = p.add_run(f"　{location}")
    r3.bold = True
    r3.font.size = Pt(10.5)
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(2)
    for label, text in (
        ("原文/现状：", current),
        ("问题：", issue),
        ("依据：", basis),
        ("建议：", suggestion),
    ):
        sp = doc.add_paragraph()
        sr = sp.add_run(label)
        sr.bold = True
        sr.font.size = Pt(10.5)
        tr = sp.add_run(text)
        tr.font.size = Pt(10.5)
        sp.paragraph_format.left_indent = Cm(0.6)
        sp.paragraph_format.space_after = Pt(2)


def bullets(doc, items, size=10.5):
    for it in items:
        p = doc.add_paragraph(it, style="List Bullet")
        for r in p.runs:
            r.font.size = Pt(size)
        p.paragraph_format.space_after = Pt(2)


def table(doc, header, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    for i, txt in enumerate(header):
        cell = t.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(txt)
        run.bold = True
        run.font.size = Pt(10)
    for row in rows:
        cells = t.add_row().cells
        for i, txt in enumerate(row):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(str(txt))
            run.font.size = Pt(10)
    if widths:
        for r in t.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = Cm(w)
    return t


